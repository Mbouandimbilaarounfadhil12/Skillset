// Returns job titles for a domain, or empty array
export function getJobsForDomain(domain) {
  if (!domain) return []
  // Exact match first
  if (DOMAIN_JOBS[domain]) return DOMAIN_JOBS[domain]
  // Partial match fallback
  const key = Object.keys(DOMAIN_JOBS).find(k =>
    k.toLowerCase().includes(domain.toLowerCase()) ||
    domain.toLowerCase().includes(k.toLowerCase())
  )
  return key ? DOMAIN_JOBS[key] : []
}
